// Flow-chaser for the pump.fun bonding-curve replay (agent-fun/replay/v2).
//
// First-principles design, calibrated on the kit's dev window. A curve's price is
// virtual_quote / virtual_token, so it only climbs while net SOL flows in. The tape
// of a launch tells you most of what matters in its first few slots: whether the
// creator front-ran it, whether a crowd or a cluster piled in, and whether fresh
// money is still arriving. This bot therefore waits for the tape to develop (age
// 1-8 slots) instead of sniping the create slot, and only buys when the flow is
// still positive: at least two distinct non-creator buyers in the recent window
// and non-negative net SOL flow over the last 15 slots.
//
// Sizing respects the replay's own cap (buys per reply <= 1% of the curve's real
// SOL reserve), so the first buy is small and the stake is built up in tranches
// only while the price keeps stepping up and flow stays non-negative. Exits are
// staged: half off at +18%, the rest rides to +40% under a trailing stop armed at
// +20%, with a -12% stop-loss and a 30-slot hold cap. A creator sell while held
// exits at once.
//
// Guardrail awareness: the run needs round trips of >= 0.01 SOL on at least 20
// coins, so the entry filter is deliberately permissive (roughly one launch in
// six should pass) and the stake per coin (0.08 SOL) is built from tranches that
// each clear the 0.01 SOL bar on their own.
//
// Deterministic by construction: no clock, no randomness, no I/O. Every decision
// is a pure function of the batches, iterated in insertion order only.

import { BPS, type Batch, type BotState, type OrderInput, type Pubkey } from './vendor/makefun-bot.ts';

export interface Params {
  /** Youngest age (slots since create) at which a coin may be bought. */
  minAge: number;
  /** Oldest age at which a first buy may still be decided. */
  maxAge: number;
  /** Lamports aimed for per coin in total across all tranches. */
  stakeLamports: number;
  /** Lamports of the first tranche (capped by 1% of real SOL per reply). */
  firstLamports: number;
  /** Lamports per add-on tranche. */
  addLamports: number;
  /** Adds after the first buy, each on a later batch, while the coin keeps qualifying. */
  maxAdds: number;
  /** An add needs the price at least this far (bps) above the previous buy's decision price. */
  addStepBps: number;
  /** An add waits this many slots after the previous buy was decided. */
  addDelay: number;
  /** An add needs the recent net flow at least this (lamports). */
  addMinFlowLamports: number;
  /** Smallest single buy worth paying the tx fee for. */
  minBuyLamports: number;
  /** Real SOL reserve window at decision time (lamports). */
  minRealSol: number;
  maxRealSol: number;
  /** Creator's own buys in the create slot: at most this (lamports). */
  maxDevBuy: number;
  /** Trades seen and distinct (non-creator) buyers seen before entry. */
  minTrades: number;
  minBuyers: number;
  /** Distinct non-creator buyers before entry, at most. */
  maxBuyers: number;
  /** Lamports sold by others / lamports bought, as bps, at most. */
  maxSellRatioBps: number;
  /** Largest single non-creator sell seen, as bps of the real SOL reserve before it, at most. */
  maxBigSellBps: number;
  /** Price now over the create price, as bps: window. */
  minRunupBps: number;
  maxRunupBps: number;
  /** The recent-flow window (slots) and what it must show. */
  flowWindow: number;
  minFlowLamports: number;
  minRecentBuyers: number;
  /** Creator sold before entry: skip the coin. */
  skipDevSold: boolean;
  /** Slippage allowed on buys (bps). */
  buySlippageBps: number;
  /** First take-profit: sell tp1PartBps of the position once it is worth tp1Bps over its cost. */
  tp1Bps: number;
  tp1PartBps: number;
  /** After the first take-profit, the rest stops out at this much under its cost (bps). */
  slAfterTp1Bps: number;
  /** Exit when the position is worth this much over its cost (bps). */
  tpBps: number;
  /** Exit when it is worth this much under its cost (bps). */
  slBps: number;
  /** Trailing stop: once up at least trailArmBps, exit on a fall of trailBps from the best value. */
  trailArmBps: number;
  trailBps: number;
  /** Exit after holding this many slots. */
  maxHold: number;
  /** Exit when the creator sells while held. */
  exitOnDevSell: boolean;
  /** Exit when no trade has hit the coin for this many slots. */
  staleSlots: number;
}

